//! 8x8 bitmap font, byte-for-byte identical to the C host (cmd/vex/main.c)
//! and the web host (cmd/vex-web/assets/vex.js) so text() renders the same
//! everywhere. Glyphs cover ASCII 32..127; `glyphs[c - first]` packs one glyph
//! as a u64 whose most-significant byte is the top row and whose
//! most-significant bit of each byte is the left pixel.

pub const first = 32;
pub const width = 8;
pub const height = 8;

/// One row of glyph `index` (bit 7 = leftmost pixel).
pub inline fn row(index: usize, y: u3) u8 {
    return @truncate(glyphs[index] >> (@as(u6, 7 - y) * 8));
}

